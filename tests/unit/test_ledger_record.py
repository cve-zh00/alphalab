"""Unit tests for :class:`TrialRecord`, :class:`TrialMetrics`, and errors."""

from __future__ import annotations

from datetime import UTC, date, datetime

import pytest
from pydantic import ValidationError

from alphalab.domain.ledger import (
    ImmutableLedgerError,
    LedgerError,
    TrialMetrics,
    TrialRecord,
    new_trial_id,
    spec_hash,
)


def _metrics() -> TrialMetrics:
    return TrialMetrics(
        sharpe_gross=1.5,
        sharpe_net=1.1,
        return_gross=0.25,
        return_net=0.19,
        max_drawdown=-0.12,
    )


def _record(**overrides: object) -> TrialRecord:
    base: dict[str, object] = {
        "recorded_at": datetime(2026, 1, 2, tzinfo=UTC),
        "spec_hash": "deadbeef",
        "dataset_hash": "cafef00d",
        "family": "momentum",
        "window_start": date(2020, 1, 1),
        "window_end": date(2021, 1, 1),
        "params": {"lookback": 20},
        "metrics": _metrics(),
    }
    base.update(overrides)
    return TrialRecord(**base)  # type: ignore[arg-type]


class TestImmutability:
    def test_record_is_frozen(self) -> None:
        # Arrange
        record = _record()

        # Act / Assert
        with pytest.raises(ValidationError):
            record.family = "mean_reversion"  # type: ignore[misc]

    def test_metrics_are_frozen(self) -> None:
        # Arrange
        metrics = _metrics()

        # Act / Assert
        with pytest.raises(ValidationError):
            metrics.sharpe_net = 9.9  # type: ignore[misc]


class TestTrialMetrics:
    def test_requires_both_gross_and_net_sharpe(self) -> None:
        # Act / Assert: omitting sharpe_net must fail -> cannot record gross only.
        with pytest.raises(ValidationError):
            TrialMetrics(  # type: ignore[call-arg]
                sharpe_gross=1.0,
                return_gross=0.1,
                return_net=0.05,
                max_drawdown=-0.1,
            )

    def test_positive_drawdown_rejected(self) -> None:
        # Act / Assert
        with pytest.raises(ValidationError):
            TrialMetrics(
                sharpe_gross=1.0,
                sharpe_net=0.9,
                return_gross=0.1,
                return_net=0.05,
                max_drawdown=0.1,
            )


class TestTrialId:
    def test_default_ids_are_unique(self) -> None:
        # Act
        ids = {new_trial_id() for _ in range(1000)}

        # Assert
        assert len(ids) == 1000

    def test_record_gets_autogenerated_id(self) -> None:
        # Act
        a = _record()
        b = _record()

        # Assert
        assert a.trial_id != b.trial_id


class TestWindowValidation:
    def test_end_before_start_rejected(self) -> None:
        # Act / Assert
        with pytest.raises(ValidationError):
            _record(window_start=date(2021, 1, 1), window_end=date(2020, 1, 1))

    def test_equal_window_allowed(self) -> None:
        # Act
        record = _record(window_start=date(2020, 1, 1), window_end=date(2020, 1, 1))

        # Assert
        assert record.window_start == record.window_end


class TestLlmMetadata:
    def test_llm_fields_default_to_none(self) -> None:
        # Act
        record = _record()

        # Assert
        assert record.llm_version is None
        assert record.llm_cutoff is None

    def test_llm_fields_are_first_class(self) -> None:
        # Act
        record = _record(llm_version="frontier-2026-09", llm_cutoff=date(2026, 9, 1))

        # Assert
        assert record.llm_version == "frontier-2026-09"
        assert record.llm_cutoff == date(2026, 9, 1)


class TestCreateConstructor:
    def test_create_derives_spec_hash_canonically(self) -> None:
        # Arrange
        spec_a = {"lookback": 20, "threshold": 1.5}
        spec_b = {"threshold": 1.5, "lookback": 20}

        # Act
        rec_a = TrialRecord.create(
            spec=spec_a,
            dataset_hash="d1",
            family="momentum",
            window_start=date(2020, 1, 1),
            window_end=date(2021, 1, 1),
            params=spec_a,
            metrics=_metrics(),
            recorded_at=datetime(2026, 1, 1, tzinfo=UTC),
        )
        rec_b = TrialRecord.create(
            spec=spec_b,
            dataset_hash="d1",
            family="momentum",
            window_start=date(2020, 1, 1),
            window_end=date(2021, 1, 1),
            params=spec_b,
            metrics=_metrics(),
            recorded_at=datetime(2026, 1, 1, tzinfo=UTC),
        )

        # Assert: equivalent specs share a spec_hash but are distinct trials.
        assert rec_a.spec_hash == rec_b.spec_hash == spec_hash(spec_a)
        assert rec_a.trial_id != rec_b.trial_id


def test_error_hierarchy() -> None:
    # Arrange / Act / Assert
    assert issubclass(ImmutableLedgerError, LedgerError)
    assert issubclass(LedgerError, Exception)
